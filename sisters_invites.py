# ── Daily limits by tier ───────────────────────────────────────────────────────

class SisterTier(str, enum.Enum):
    FOUNDER = "founder"   # Unlimited
    CIRCLE  = "circle"    # 20/day
    MEMBER  = "member"    # 0 for 24hrs, then 5/day for 30 days, then 10/day

DAILY_LIMITS = {
    SisterTier.FOUNDER: None,   # None = unlimited
    SisterTier.CIRCLE:  20,
    SisterTier.MEMBER:  10,     # after 30 days
}

MEMBER_EARLY_LIMIT   = 5   # days 2–30
MEMBER_WAITING_HOURS = 24  # first 24hrs = 0 codes


# ── InviteCode Model ──────────────────────────────────────────────────────────

class InviteCode(Base):
    """
    A single-use invite code generated by a Sister.

    Lifecycle:
      ACTIVE   → can be used to register
      USED     → registration complete, used_by set
      REVOKED  → cancelled by the generator before use
      EXPIRED  → 7 days elapsed without use

    The invite chain is permanent — even after a code is used,
    the link between inviter and invitee is retained for accountability.
    """
    __tablename__ = "sister_invite_codes"

    CODE_LENGTH  = 12
    TTL_DAYS     = 7

    id           = Column(Integer, primary_key=True, index=True)
    code         = Column(String(20), unique=True, index=True, nullable=False)

    # Who generated it
    generated_by = Column(Integer, ForeignKey("sisters.id"), nullable=False)

    # Who used it (set on registration)
    used_by      = Column(Integer, ForeignKey("sisters.id"), nullable=True)

    # Status
    status       = Column(String(10), default="active")  # active/used/revoked/expired

    # Timing
    created_at   = Column(DateTime, default=lambda: datetime.now(timezone.utc))
    expires_at   = Column(DateTime, nullable=False)
    used_at      = Column(DateTime, nullable=True)

    # Relationships
    generator    = relationship("Sister", foreign_keys=[generated_by])
    invitee      = relationship("Sister", foreign_keys=[used_by])

    @staticmethod
    def generate_code() -> str:
        """
        Generate a readable invite code.
        Format: SSTR-XXXX-XXXX
        Avoids ambiguous characters (0/O, 1/I/l).
        """
        chars = string.ascii_uppercase.replace('O', '').replace('I', '') + \
                string.digits.replace('0', '').replace('1', '')
        part1 = ''.join(secrets.choice(chars) for _ in range(4))
        part2 = ''.join(secrets.choice(chars) for _ in range(4))
        return f"SSTR-{part1}-{part2}"


# ── Sister Tier extension ─────────────────────────────────────────────────────
# We add tier and daily tracking to the Sister model via a separate table
# to avoid modifying the core sister record structure.

class SisterTierRecord(Base):
    """
    Tracks a Sister's tier and daily invite usage.
    Separate from the main Sister model for clean separation.
    """
    __tablename__ = "sister_tiers"

    id             = Column(Integer, primary_key=True)
    sister_id      = Column(Integer, ForeignKey("sisters.id"), unique=True, nullable=False)
    tier           = Column(String(10), default=SisterTier.MEMBER)
    codes_today    = Column(Integer, default=0)
    last_reset     = Column(Date, default=lambda: date.today())

    # Invite tree — who invited this Sister (NULL for founder)
    invited_by     = Column(Integer, ForeignKey("sisters.id"), nullable=True)

    sister         = relationship("Sister", foreign_keys=[sister_id])
    inviter        = relationship("Sister", foreign_keys=[invited_by])


